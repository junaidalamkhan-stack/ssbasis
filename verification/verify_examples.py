"""
verify_examples.py -- independent re-computation of the tables and claims of
the examples of the manuscript, without Singular.  Labels use the numbering of
the REVISED manuscript (old 1.5, 4.1, 4.3, 4.4 are now 1.6, 4.2, 4.4, 4.5).

For each example we check, with exact arithmetic over the stated coefficient
ring:
  (1) degrees and leading forms of the generators;
  (2) pi(c) = 0 and Omega-homogeneity of each claimed generator of ker(pi),
      and the stated value of Omega(c);
  (3) psi(l) = 0 and Omega-LF(l) = c for each claimed lifting l;
  (4) for claimed non-liftable c: an exhaustive linear-algebra test
      (only for gradings whose lower sets are finite);
  (5) generation of ker(pi) by the claimed set, degree by degree up to a
      bound (a necessary check; full proofs of generation are by hand,
      see the report).
Run:  python3 verify_examples.py
"""
from sslib import *

RESULTS = []

def record(ex, item, ok, note=''):
    RESULTS.append((ex, item, ok, note))
    print(('  [ OK ] ' if ok else '  [FAIL] ') + item + (('  -- ' + note) if note else ''))

def degree_boxes(k, box):
    """All gamma in N^k with gamma <= box componentwise."""
    import itertools
    return [g for g in itertools.product(*[range(b + 1) for b in box])]

def run_example(name, xnames, mod, W, F_str, claimed_LF, claimed_deg, U_str,
                claimed_Omega, liftings, nonliftable=(), gen_box=None,
                kill=(), finite_lower_sets=True, extra=None):
    print('\n=== %s  (coefficients %s) ===' % (name, 'Z' if mod == 0 else 'Z/%d' % mod))
    nx = len(xnames)
    F = [quotient_reduce(parse(s, xnames), mod, kill) for s in F_str]
    F = [clean(f, mod) for f in F]
    LF = [lead_form(f, W) for f in F]
    D = [deg(f, W) for f in F]
    m = len(F)
    ynames = ['Y%d' % (i + 1) for i in range(m)]
    # (1)
    for i in range(m):
        cl = clean(parse(claimed_LF[i], xnames), mod)
        record(name, 'LF(f%d) = %s, degree %s' % (i + 1, claimed_LF[i], claimed_deg[i]),
               LF[i] == cl and D[i] == tuple(claimed_deg[i]),
               '' if LF[i] == cl and D[i] == tuple(claimed_deg[i]) else
               'computed LF=%s deg=%s' % (fmt(LF[i], xnames), D[i]))
    U = [clean(parse(s, ynames), mod) for s in U_str]
    # (2)
    for c, s, om in zip(U, U_str, claimed_Omega):
        piv = subst(c, LF, mod, nx, kill)
        hom = is_homog(c, D)
        record(name, 'pi(%s) = 0' % s, piv == {}, '' if piv == {} else 'pi = ' + fmt(piv, xnames))
        record(name, '%s is Omega-homogeneous with Omega = %s' % (s, om),
               hom and Omega(c, D) == tuple(om),
               '' if hom and Omega(c, D) == tuple(om) else 'Omega=%s homog=%s' % (Omega(c, D), hom))
    # (3)
    for (cs, ls) in liftings:
        c = clean(parse(cs, ynames), mod)
        l = clean(parse(ls, ynames), mod)
        ps = subst(l, F, mod, nx, kill)
        olf = OLF(l, D)
        record(name, 'lifting of %s: psi(%s) = 0' % (cs, ls), ps == {},
               '' if ps == {} else 'psi = ' + fmt(ps, xnames))
        record(name, 'Omega-LF(lifting) = %s' % cs, olf == c,
               '' if olf == c else 'OLF = ' + fmt(olf, ynames))
    # (4)
    for cs in nonliftable:
        c = clean(parse(cs, ynames), mod)
        psi_c = subst(c, F, mod, nx, kill)
        if finite_lower_sets:
            ok, _ = liftable(c, F, D, mod, nx, kill)
            record(name, '%s has NO lifting (exhaustive test); psi(c) = %s' % (cs, fmt(psi_c, xnames)),
                   not ok)
    # (5)
    if gen_box is not None:
        bad = []
        checked = 0
        for g in degree_boxes(len(W), gen_box):
            if not any(g):
                continue
            try:
                ok, a, b = kernel_generated_in_degree(U, LF, D, mod, nx, tuple(g), kill)
            except ValueError:
                continue
            checked += 1
            if not ok:
                bad.append((g, a, b))
        record(name, 'ker(pi) generated by the claimed set in all %d degrees <= %s' % (checked, gen_box),
               not bad, '' if not bad else 'first failures: %s' % bad[:3])
    if extra:
        extra(F, LF, D, xnames, ynames)

