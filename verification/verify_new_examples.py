"""
verify_new_examples.py -- independent checks (no Singular) of the two
examples added in the revision:
  (A) R = K[x,y]/(x^2), natural grading, f = y + xy   (char 0, 2, 3)
  (B) S = Q[e]/(e^2), R = S[x,y], deg x = 1, deg y = 2, F = {x+y, e*y}
In (B) coefficients in S are handled by treating e as a variable of degree 0
with e^2 = 0; an S-span is the Q-span of {p, e*p}.
Run: python3 verify_new_examples.py
"""
from sslib import *

ok_all = True
def check(label, cond):
    global ok_all
    ok_all &= bool(cond)
    print(('  [ OK ] ' if cond else '  [FAIL] ') + label)

# ---------------------------------------------------------------- (A)
print('(A) R = K[x,y]/(x^2), natural grading, f = y + xy')
X = ['x', 'y']; kill = [(2, 0)]; W = [[1, 1]]
f = parse('y+x*y', X)
for p in (0, 2, 3):
    fp = clean(f, p)
    good = True
    for n in range(1, 13):
        fn = quotient_reduce(power(fp, n, p, 2), p, kill)
        if fn != clean({(0, n): 1, (1, n): n}, p):
            good = False
    check('char %d: f^n = y^n + n*x*y^n for 1 <= n <= 12' % p, good)
    LF = [lead_form(fp, W)]; D = [deg(fp, W)]
    U = [parse('Y1^2', ['Y1'])]
    gen = all(kernel_generated_in_degree(U, LF, D, p, 2, (g,), kill)[0] for g in range(1, 13))
    check('char %d: F = {f}: ker(pi) = <Y1^2> in all degrees <= 12' % p, gen)
    lift, _ = liftable(U[0], [fp], D, p, 2, kill)
    check('char %d: F = {f}: Y1^2 does not lift, so {f} is not an SS-basis' % p, not lift)

# char 0: K[Y(A)] in degrees <= 10 equals K + span{x y^n}: leading forms of all
# h = sum a_n f^n with a_N != 0 are N a_N x y^N
p = 0
good = True
for N in range(1, 10):
    # the leading form of f^N + (lower powers) is N x y^N; check with random lower terms
    import random
    rng = random.Random(N)
    h = {}
    for n in range(0, N + 1):
        a = rng.randint(-3, 3) if n < N else rng.choice([1, 2, -1])
        h = add(h, scal(a, quotient_reduce(power(f, n, 0, 2), 0, kill), 0), 0)
    lf = lead_form(h, W)
    lc = h.get((1, N), 0)
    if not (deg(h, W) == (N + 1,) and set(lf) == {(1, N)}):
        good = False
check('char 0: Y(h) is a multiple of x*y^N, deg h = N+1, for h of f-degree N <= 9', good)
# the products of two leading forms x y^a * x y^b vanish
check('char 0: (x*y^a)(x*y^b) = 0 in R', quotient_reduce(mul({(1, 2): 1}, {(1, 3): 1}, 0), 0, kill) == {})

# char 2: {f, f^2} = {f, y^2}; char 3: {f, f^2, f^3}: SS-bases (lifting test)
for p, Fs, Us, Ls in [
    (2, ['y+x*y', 'y^2'], ['Y1^2'], ['Y1^2+Y2']),
    (3, ['y+x*y', 'y^2+2*x*y^2', 'y^3'], ['Y1^2', 'Y1*Y2', 'Y2^2'],
        ['Y1^2-Y2', 'Y1*Y2-Y3', 'Y2^2-Y1*Y3'])]:
    F = [clean(parse(s, X), p) for s in Fs]
    LF = [lead_form(g, W) for g in F]; D = [deg(g, W) for g in F]
    yn = ['Y%d' % (i + 1) for i in range(len(F))]
    U = [clean(parse(s, yn), p) for s in Us]
    check('char %d: claimed generators lie in ker(pi) and are homogeneous' % p,
          all(subst(u, LF, p, 2, kill) == {} and is_homog(u, D) for u in U))
    gen = all(kernel_generated_in_degree(U, LF, D, p, 2, (g,), kill)[0] for g in range(1, 13))
    check('char %d: they generate ker(pi) in all degrees <= 12' % p, gen)
    good = True
    for u, ls in zip(U, Ls):
        l = clean(parse(ls, yn), p)
        if subst(l, F, p, 2, kill) != {} or OLF(l, D) != u:
            good = False
    check('char %d: liftings %s are valid' % (p, ', '.join(Ls)), good)

# ---------------------------------------------------------------- (B)
print('(B) S = Q[e]/(e^2), deg e = 0, deg x = 1, deg y = 2')
XB = ['e', 'x', 'y']; killB = [(2, 0, 0)]; WB = [[0, 1, 2]]; p = 0
def e_times(q):
    return quotient_reduce(mul({(1, 0, 0): 1}, q, 0), 0, killB)
F = [parse('x+y', XB), parse('e*y', XB)]
LF = [lead_form(g, WB) for g in F]; D = [deg(g, WB) for g in F]
check('Y(x+y) = y and Y(e*y) = e*y, both of degree 2',
      LF[0] == parse('y', XB) and LF[1] == parse('e*y', XB) and D == [(2,), (2,)])
# u = e*Y1 - Y2: pi(u) = e*y - e*y = 0, psi(u) = e*x
u_img = add(e_times(LF[0]), scal(-1, LF[1], 0), 0)
check('pi(e*Y1 - Y2) = 0', u_img == {})
psi_u = add(e_times(F[0]), scal(-1, F[1], 0), 0)
check('psi(e*Y1 - Y2) = e*x (degree 1)', psi_u == parse('e*x', XB))
# no lifting: e*x is not an S-combination of psi(Y^alpha) with deg alpha < 2, i.e. of 1
check('psi(e*Y1 - Y2) = e*x has degree 1, below Omega = 2; deg Y_i = 2, so only alpha = 0 has smaller degree',
      True)  # see the next line
span = [{(0, 0, 0): 1}, {(1, 0, 0): 1}]          # Q-basis of S*1
mons = sorted({e for q in span + [psi_u] for e in q})
inS = in_span([[q.get(e, 0) for e in mons] for q in span], [psi_u.get(e, 0) for e in mons], 0, len(mons))
check('  (e*x not in the Q-span of 1, e)', not inS)
# kernel of pi for F = {x+y, e*y}: generated by e*Y1 - Y2 (degrees <= 10)
def kernel_check(Flist, Ulist, ymax):
    LFl = [lead_form(g, WB) for g in Flist]; Dl = [deg(g, WB) for g in Flist]
    m = len(Flist); yn = ['Y%d' % (i + 1) for i in range(m)]
    U = [parse(s, ['e'] + yn) for s in Ulist]   # e as an extra variable of the Y-ring
    good = True
    for g in range(1, ymax + 1):
        alphas = y_monomials_of_degree(Dl, (g,))
        basis = [((j,) + a) for a in alphas for j in (0, 1)]     # e^j Y^alpha
        if not basis:
            continue
        idx = {b: i for i, b in enumerate(basis)}
        def img(b):
            q = {(0, 0, 0): 1} if b[0] == 0 else {(1, 0, 0): 1}
            for i, k in enumerate(b[1:]):
                for _ in range(k):
                    q = quotient_reduce(mul(q, LFl[i], 0), 0, killB)
            return q
        imgs = [img(b) for b in basis]
        xm = sorted({e for q in imgs for e in q})
        rk = rank_field([[q.get(e, 0) for e in xm] for q in imgs], 0) if xm else 0
        dimker = len(basis) - rk
        gens = []
        for u in U:
            du = max(sum(k * Dl[i][0] for i, k in enumerate(t[1:])) for t in u)
            if du > g:
                continue
            for beta in ([tuple([0] * m)] if du == g else y_monomials_of_degree(Dl, (g - du,))):
                for j in (0, 1):
                    v = [0] * len(basis)
                    for t, c in u.items():
                        jj = t[0] + j
                        if jj > 1:
                            continue
                        key = (jj,) + tuple(a + b for a, b in zip(t[1:], beta))
                        v[idx[key]] += c
                    gens.append(v)
        ds = rank_field(gens, 0) if gens else 0
        if ds != dimker:
            good = False
    return good
check('F = {x+y, e*y}: ker(pi) = <e*Y1 - Y2> in all degrees <= 10',
      kernel_check(F, ['e*Y1-Y2'], 10))
# completed set F' = {x+y, e*y, e*x}
F2 = F + [parse('e*x', XB)]
check("e*x = e*f1 - f2 lies in A", add(e_times(F[0]), scal(-1, F[1], 0), 0) == F2[2])
check("F': ker(pi') = <e*Y1 - Y2, e*Y3, Y3^2> in all degrees <= 10",
      kernel_check(F2, ['e*Y1-Y2', 'e*Y3', 'Y3^2'], 10))
def psiB(Ls, Flist):
    m = len(Flist); L = parse(Ls, ['e'] + ['Y%d' % (i + 1) for i in range(m)])
    tot = {}
    for t, c in L.items():
        q = {(0, 0, 0): c} if t[0] == 0 else {(1, 0, 0): c}
        for i, k in enumerate(t[1:]):
            for _ in range(k):
                q = quotient_reduce(mul(q, Flist[i], 0), 0, killB)
        tot = add(tot, q, 0)
    return quotient_reduce(tot, 0, killB)
check("liftings e*Y1 - Y2 - Y3, e*Y3, Y3^2 lie in ker(psi')",
      all(psiB(s, F2) == {} for s in ['e*Y1-Y2-Y3', 'e*Y3', 'Y3^2']))
check("e*x has degree 1 < 2 = Omega(e*Y1 - Y2); f3^2 = 0 while Omega(Y3^2) = 2",
      deg(F2[2], WB) == (1,) and quotient_reduce(mul(F2[2], F2[2], 0), 0, killB) == {})
# natural grading: both generators homogeneous of degree 1, so an SS-basis
WN = [[0, 1, 1]]
check('natural grading: x+y and e*y are homogeneous of degree 1',
      all(lead_form(g, WN) == g for g in F) and [deg(g, WN) for g in F] == [(1,), (1,)])

print('\nALL CHECKS PASSED' if ok_all else '\nSOME CHECK FAILED')
